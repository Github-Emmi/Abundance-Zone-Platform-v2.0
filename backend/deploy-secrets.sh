#!/bin/bash
set -eo pipefail

echo "🔐 Setting secrets for Fly.io apps..."

# Load environment variables
export $(grep -v '^#' .env | grep -v '^$' | xargs)

echo "📡 Setting secrets for abundance-zone-api..."
flyctl secrets set \
  "DATABASE_URL=${DATABASE_URL}" \
  "REDIS_URL=${REDIS_URL}" \
  "CELERY_BROKER_URL=${CELERY_BROKER_URL}" \
  "CELERY_RESULT_BACKEND=${CELERY_RESULT_BACKEND}" \
  "JWT_SECRET_KEY=${JWT_SECRET_KEY}" \
  "JWT_REFRESH_SECRET_KEY=${JWT_REFRESH_SECRET_KEY}" \
  "OPENAI_API_KEY=${OPENAI_API_KEY}" \
  "GOOGLE_API_KEY=${GOOGLE_API_KEY}" \
  "CLOUDINARY_CLOUD_NAME=${CLOUDINARY_CLOUD_NAME}" \
  "CLOUDINARY_API_KEY=${CLOUDINARY_API_KEY}" \
  "CLOUDINARY_API_SECRET=${CLOUDINARY_API_SECRET}" \
  "RESEND_API_KEY=${RESEND_API_KEY}" \
  "FIREBASE_PROJECT_ID=${FIREBASE_PROJECT_ID}" \
  "FIREBASE_PRIVATE_KEY_ID=${FIREBASE_PRIVATE_KEY_ID}" \
  "FIREBASE_PRIVATE_KEY=${FIREBASE_PRIVATE_KEY}" \
  "FIREBASE_CLIENT_EMAIL=${FIREBASE_CLIENT_EMAIL}" \
  "SENTRY_DSN=${SENTRY_DSN}" \
  "ENVIRONMENT=production" \
  "PORT=8000" \
  --app abundance-zone-api

echo "🔨 Setting secrets for abundance-zone-worker..."
flyctl secrets set \
  "DATABASE_URL=${DATABASE_URL}" \
  "REDIS_URL=${REDIS_URL}" \
  "CELERY_BROKER_URL=${CELERY_BROKER_URL}" \
  "CELERY_RESULT_BACKEND=${CELERY_RESULT_BACKEND}" \
  "OPENAI_API_KEY=${OPENAI_API_KEY}" \
  "GOOGLE_API_KEY=${GOOGLE_API_KEY}" \
  "CLOUDINARY_CLOUD_NAME=${CLOUDINARY_CLOUD_NAME}" \
  "CLOUDINARY_API_KEY=${CLOUDINARY_API_KEY}" \
  "CLOUDINARY_API_SECRET=${CLOUDINARY_API_SECRET}" \
  "RESEND_API_KEY=${RESEND_API_KEY}" \
  "FIREBASE_PROJECT_ID=${FIREBASE_PROJECT_ID}" \
  "FIREBASE_PRIVATE_KEY_ID=${FIREBASE_PRIVATE_KEY_ID}" \
  "FIREBASE_PRIVATE_KEY=${FIREBASE_PRIVATE_KEY}" \
  "FIREBASE_CLIENT_EMAIL=${FIREBASE_CLIENT_EMAIL}" \
  "SENTRY_DSN=${SENTRY_DSN}" \
  "ENVIRONMENT=production" \
  --app abundance-zone-worker

echo "⏰ Setting secrets for abundance-zone-beat..."
flyctl secrets set \
  "DATABASE_URL=${DATABASE_URL}" \
  "REDIS_URL=${REDIS_URL}" \
  "CELERY_BROKER_URL=${CELERY_BROKER_URL}" \
  "CELERY_RESULT_BACKEND=${CELERY_RESULT_BACKEND}" \
  "RESEND_API_KEY=${RESEND_API_KEY}" \
  "FIREBASE_PROJECT_ID=${FIREBASE_PROJECT_ID}" \
  "FIREBASE_PRIVATE_KEY_ID=${FIREBASE_PRIVATE_KEY_ID}" \
  "FIREBASE_PRIVATE_KEY=${FIREBASE_PRIVATE_KEY}" \
  "FIREBASE_CLIENT_EMAIL=${FIREBASE_CLIENT_EMAIL}" \
  "ENVIRONMENT=production" \
  --app abundance-zone-beat

echo "✅ All secrets set successfully!"
